package models

import (
	"time"

	"github.com/google/uuid"
	"gorm.io/gorm"
)

// ShopeeBooking represents a Shopee booking (pickup/shipping booking) in database
// Matches PostgreSQL schema: shopee_bookings
type ShopeeBooking struct {
	ID                  string         `gorm:"column:id;primaryKey;type:varchar(36)" json:"id"`
	TenantID            string         `gorm:"column:tenant_id;type:varchar(50);not null;index:idx_booking_tenant_shop_sn,unique,priority:1" json:"tenant_id"`
	ShopID              uint64         `gorm:"column:shop_id;not null;index:idx_booking_tenant_shop_sn,unique,priority:2" json:"shop_id"`
	BookingSN           string         `gorm:"column:booking_sn;type:varchar(100);not null;index:idx_booking_tenant_shop_sn,unique,priority:3" json:"booking_sn"`
	OrderSN             string         `gorm:"column:order_sn;type:varchar(100);index" json:"order_sn"`
	BookingStatus       string         `gorm:"column:booking_status;type:varchar(50);index" json:"booking_status"`
	MatchStatus         string         `gorm:"column:match_status;type:varchar(50)" json:"match_status"`
	Region              string         `gorm:"column:region;type:varchar(20)" json:"region"`
	ShippingCarrier     string         `gorm:"column:shipping_carrier;type:varchar(100)" json:"shipping_carrier"`
	RecipientName       string         `gorm:"column:recipient_name;type:varchar(200)" json:"recipient_name"`
	RecipientPhone      string         `gorm:"column:recipient_phone;type:varchar(50)" json:"recipient_phone"`
	RecipientAddressJSON string        `gorm:"column:recipient_address_json;type:text" json:"recipient_address_json"`
	FulfillmentFlag     string         `gorm:"column:fulfillment_flag;type:varchar(50)" json:"fulfillment_flag"`
	CreateTime          int64          `gorm:"column:create_time" json:"create_time"`
	UpdateTime          int64          `gorm:"column:update_time" json:"update_time"`
	PickupDoneTime      int64          `gorm:"column:pickup_done_time" json:"pickup_done_time"`
	RawData             string         `gorm:"column:raw_data;type:text" json:"-"`
	SyncedAt            time.Time      `gorm:"column:synced_at;autoUpdateTime" json:"synced_at"`
	CreatedAt           time.Time      `gorm:"column:created_at" json:"created_at"`
	UpdatedAt           time.Time      `gorm:"column:updated_at" json:"updated_at"`
	DeletedAt           gorm.DeletedAt `gorm:"index" json:"-"`
}

// TableName specifies the table name for GORM
func (ShopeeBooking) TableName() string {
	return GetTableName("ShopeeBooking")
}

// BeforeCreate generates UUID for ShopeeBooking if ID is empty
func (b *ShopeeBooking) BeforeCreate(tx *gorm.DB) error {
	if b.ID == "" {
		b.ID = uuid.New().String()
	}
	return nil
}

// ShopeeBookingItem represents an item within a Shopee booking
// Matches PostgreSQL schema: shopee_booking_items
// LineKey is a deterministic concatenation: item_id|model_id|item_sku|model_sku|item_name|model_name
// with empty components preserved. Generated by repository/service layer before insert.
type ShopeeBookingItem struct {
	ID               string    `gorm:"column:id;primaryKey;type:varchar(36)" json:"id"`
	TenantID         string    `gorm:"column:tenant_id;type:varchar(50);not null;index:idx_booking_item_tenant_shop_sn_line,unique,priority:1" json:"tenant_id"`
	ShopID           uint64    `gorm:"column:shop_id;not null;index:idx_booking_item_tenant_shop_sn_line,unique,priority:2" json:"shop_id"`
	BookingSN        string    `gorm:"column:booking_sn;type:varchar(100);not null;index:idx_booking_item_tenant_shop_sn_line,unique,priority:3;index:idx_booking_sn_items" json:"booking_sn"`
	LineKey          string    `gorm:"column:line_key;type:varchar(500);not null;index:idx_booking_item_tenant_shop_sn_line,unique,priority:4" json:"line_key"`
	ItemID           int64     `gorm:"column:item_id" json:"item_id"`
	ModelID          int64     `gorm:"column:model_id" json:"model_id"`
	ItemName         string    `gorm:"column:item_name;type:varchar(500)" json:"item_name"`
	ModelName        string    `gorm:"column:model_name;type:varchar(500)" json:"model_name"`
	ItemSku          string    `gorm:"column:item_sku;type:varchar(200)" json:"item_sku"`
	ModelSku         string    `gorm:"column:model_sku;type:varchar(200)" json:"model_sku"`
	SKU              string    `gorm:"column:sku;type:varchar(200)" json:"sku"`
	Quantity         int       `gorm:"column:quantity" json:"quantity"`
	Weight           float64   `gorm:"column:weight" json:"weight"`
	ProductLocationID string   `gorm:"column:product_location_id;type:varchar(100)" json:"product_location_id"`
	ImageURL         string    `gorm:"column:image_url;type:text" json:"image_url"`
	RawData          string    `gorm:"column:raw_data;type:text" json:"-"`
	CreatedAt        time.Time `gorm:"column:created_at" json:"created_at"`
	UpdatedAt        time.Time `gorm:"column:updated_at" json:"updated_at"`
}

// TableName specifies the table name for GORM
func (ShopeeBookingItem) TableName() string {
	return GetTableName("ShopeeBookingItem")
}

// BeforeCreate generates UUID for ShopeeBookingItem if ID is empty
func (b *ShopeeBookingItem) BeforeCreate(tx *gorm.DB) error {
	if b.ID == "" {
		b.ID = uuid.New().String()
	}
	return nil
}
